<#
.SYNOPSIS
    Onboarding script for the Kong AI Gateway repo.
    Checks prerequisites, scaffolds credential files from templates,
    optionally downloads tool binaries, and validates the setup.

.PARAMETER CheckOnly
    Run prerequisite and credential checks without creating any files.

.PARAMETER InstallTools
    Download deck and kongctl binaries into tools\ (requires internet access).

.PARAMETER SkipNodeModules
    Skip npm install for mcp-server and mock-api.

.EXAMPLE
    .\scripts\setup-repo.ps1

.EXAMPLE
    .\scripts\setup-repo.ps1 -InstallTools

.EXAMPLE
    .\scripts\setup-repo.ps1 -CheckOnly
#>
[CmdletBinding()]
param(
    [switch]$CheckOnly,
    [switch]$InstallTools,
    [switch]$SkipNodeModules
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot

# ── Helpers ───────────────────────────────────────────────────────────────────

$passCount = 0
$warnCount = 0
$failCount = 0

function Write-Pass([string]$msg) {
    Write-Host "  ✅ $msg" -ForegroundColor Green
    $script:passCount++
}
function Write-Warn([string]$msg) {
    Write-Host "  ⚠️  $msg" -ForegroundColor Yellow
    $script:warnCount++
}
function Write-Fail([string]$msg) {
    Write-Host "  ❌ $msg" -ForegroundColor Red
    $script:failCount++
}
function Write-Section([string]$title) {
    Write-Host ""
    Write-Host "── $title " -ForegroundColor Cyan
}

function Test-Command([string]$name) {
    return [bool](Get-Command $name -ErrorAction SilentlyContinue)
}

function Test-FileCustomized([string]$path) {
    if (-not (Test-Path $path)) { return $false }
    $content = Get-Content $path -Raw
    # Match any angle-bracket placeholder regardless of case: <YOUR_KEY>, <ISO8601 timestamp>, <UUID generated by...>, etc.
    # Also catch the _instructions sentinel field used in konnect-connection.json.template.
    return -not ($content -match '<[^>]+>|_instructions')
}

# ── Section 1: Required tools ─────────────────────────────────────────────────
Write-Host ""
Write-Host "╔══════════════════════════════════════════════════╗" -ForegroundColor Cyan
Write-Host "║  Kong AI Gateway — Repo Setup                    ║" -ForegroundColor Cyan
Write-Host "╚══════════════════════════════════════════════════╝" -ForegroundColor Cyan

Write-Section "Checking Required Tools"

$requiredTools = @(
    @{ Name = 'az';      Description = 'Azure CLI — deploy infrastructure' }
    @{ Name = 'git';     Description = 'Source control' }
    @{ Name = 'node';    Description = 'MCP Server and test runtime' }
    @{ Name = 'npm';     Description = 'Node package manager' }
    @{ Name = 'python';  Description = 'JWT generation (PyJWT)'; Aliases = @('python3') }
    @{ Name = 'openssl'; Description = 'API key generation' }
    @{ Name = 'curl';    Description = 'Smoke tests (Bash path)' }
)

foreach ($tool in $requiredTools) {
    $found = Test-Command $tool.Name
    if (-not $found -and $tool.Aliases) {
        foreach ($a in $tool.Aliases) { if (Test-Command $a) { $found = $true; break } }
    }
    if ($found) {
        Write-Pass "$($tool.Name) — $($tool.Description)"
    } else {
        Write-Fail "$($tool.Name) — $($tool.Description) — NOT FOUND. See docs/repo-setup.md."
    }
}

# ── Section 2: Optional tool binaries ────────────────────────────────────────
Write-Section "Checking Optional Tool Binaries (deck / kongctl)"

$deckPath    = Join-Path $root 'tools\deck\deck.exe'
$kongctlPath = Join-Path $root 'tools\konnect-cli\kongctl.exe'

if (Test-Path $deckPath) {
    Write-Pass "deck found at tools\deck\deck.exe"
} else {
    Write-Warn "deck not found. Needed for Konnect config sync. Run with -InstallTools to download."
}

if (Test-Path $kongctlPath) {
    Write-Pass "kongctl found at tools\konnect-cli\kongctl.exe"
} else {
    Write-Warn "kongctl not found. Needed for Konnect control plane management. Run with -InstallTools to download."
}

# ── Section 3: Credential files ───────────────────────────────────────────────
Write-Section "Checking Credential Files"

$credFiles = @(
    @{
        Target   = 'api-key-config.json'
        Template = 'api-key-config.json.template'
        Purpose  = 'Kong key-auth API credential for Foundry and MCP Inspector'
    }
    @{
        Target   = 'entra-oauth-config.json'
        Template = 'entra-oauth-config.json.template'
        Purpose  = 'Azure Entra OAuth app registration details'
    }
    @{
        Target   = 'konnect-connection.json'
        Template = 'konnect-connection.json.template'
        Purpose  = 'Konnect control plane connection details'
    }
)

$filesToScaffold = @()

foreach ($cf in $credFiles) {
    $targetPath = Join-Path $root $cf.Target
    if (Test-Path $targetPath) {
        if (Test-FileCustomized $targetPath) {
            Write-Pass "$($cf.Target) — exists and appears configured"
        } else {
            Write-Warn "$($cf.Target) — exists but still contains template placeholders. Fill it in before use."
        }
    } else {
        Write-Warn "$($cf.Target) — missing. Purpose: $($cf.Purpose)"
        $filesToScaffold += $cf
    }
}

# ── Section 4: Node modules ───────────────────────────────────────────────────
Write-Section "Checking Node Modules"

$nodeProjects = @('mcp-server', 'mock-api')
foreach ($proj in $nodeProjects) {
    $nmPath = Join-Path $root "$proj\node_modules"
    if (Test-Path $nmPath) {
        Write-Pass "$proj\node_modules — installed"
    } else {
        Write-Warn "$proj\node_modules — missing. npm install required."
        $filesToScaffold += @{ NpmInstall = $proj }
    }
}

# ── Early exit for CheckOnly ───────────────────────────────────────────────────
if ($CheckOnly) {
    Write-Host ""
    Write-Host "── Summary (check-only mode) " -ForegroundColor Cyan
    Write-Host "   Pass: $passCount  Warn: $warnCount  Fail: $failCount"
    if ($failCount -gt 0) {
        Write-Host "   ❌ $failCount required tool(s) missing. See docs/repo-setup.md." -ForegroundColor Red
        exit 1
    }
    Write-Host "   Run without -CheckOnly to scaffold credential files." -ForegroundColor Yellow
    exit 0
}

# ── Section 5: Scaffold credential files ─────────────────────────────────────
if ($filesToScaffold.Count -gt 0) {
    Write-Section "Scaffolding Missing Files"

    foreach ($cf in $filesToScaffold) {
        if ($cf.NpmInstall) {
            if (-not $SkipNodeModules) {
                $projDir = Join-Path $root $cf.NpmInstall
                Write-Host "  Running npm install in $($cf.NpmInstall)..."
                Push-Location $projDir
                try {
                    npm install --silent
                    Write-Pass "npm install completed for $($cf.NpmInstall)"
                } catch {
                    Write-Warn "npm install failed for $($cf.NpmInstall): $_"
                } finally {
                    Pop-Location
                }
            }
            continue
        }

        $templatePath = Join-Path $root $cf.Template
        $targetPath   = Join-Path $root $cf.Target

        if (-not (Test-Path $templatePath)) {
            Write-Warn "Template $($cf.Template) not found — skipping $($cf.Target)"
            continue
        }

        if (-not (Test-Path $targetPath)) {
            try {
                Copy-Item $templatePath $targetPath
                Write-Pass "Created $($cf.Target) from template — fill in all <placeholder> values"
            } catch {
                Write-Fail "Could not create $($cf.Target) from template: $_"
            }
        }
    }
}

# ── Section 6: Install tool binaries ─────────────────────────────────────────
if ($InstallTools) {
    Write-Section "Downloading Tool Binaries"

    $toolsDir    = Join-Path $root 'tools'
    $deckDir     = Join-Path $toolsDir 'deck'
    $kongctlDir  = Join-Path $toolsDir 'konnect-cli'

    New-Item -ItemType Directory -Force -Path $deckDir    | Out-Null
    New-Item -ItemType Directory -Force -Path $kongctlDir | Out-Null

    # deck
    if (-not (Test-Path $deckPath)) {
        Write-Host "  Downloading deck..."
        try {
            $deckLatest = Invoke-RestMethod 'https://api.github.com/repos/Kong/deck/releases/latest'
            $deckAsset  = $deckLatest.assets | Where-Object { $_.name -match 'deck_.*_windows_amd64\.zip' } | Select-Object -First 1
            if ($deckAsset) {
                $deckZip = Join-Path $deckDir 'deck.zip'
                Invoke-WebRequest -Uri $deckAsset.browser_download_url -OutFile $deckZip -UseBasicParsing
                Expand-Archive -Path $deckZip -DestinationPath $deckDir -Force
                Remove-Item $deckZip
                # Verify binary landed at expected path. Some releases nest inside a subdirectory.
                if (-not (Test-Path $deckPath)) {
                    $found = Get-ChildItem -Path $deckDir -Recurse -Filter 'deck.exe' | Select-Object -First 1
                    if ($found) {
                        Move-Item $found.FullName $deckPath
                        Write-Pass "deck downloaded and extracted to tools\deck\deck.exe"
                    } else {
                        Write-Warn "deck extracted but deck.exe not found in tools\deck\. Check the zip contents manually."
                    }
                } else {
                    Write-Pass "deck downloaded to tools\deck\"
                }
            } else {
                Write-Warn "Could not find deck Windows release asset. Download manually from https://github.com/Kong/deck/releases"
            }
        } catch {
            Write-Warn "deck download failed: $_. Download manually from https://github.com/Kong/deck/releases"
        }
    } else {
        Write-Pass "deck already present — skipping download"
    }

    # kongctl
    if (-not (Test-Path $kongctlPath)) {
        Write-Host "  Downloading kongctl..."
        try {
            $kongctlLatest = Invoke-RestMethod 'https://api.github.com/repos/Kong/kongctl/releases/latest'
            $kongctlAsset  = $kongctlLatest.assets | Where-Object { $_.name -match 'kongctl_windows_amd64\.zip' } | Select-Object -First 1
            if ($kongctlAsset) {
                $kongctlZip = Join-Path $kongctlDir 'kongctl.zip'
                Invoke-WebRequest -Uri $kongctlAsset.browser_download_url -OutFile $kongctlZip -UseBasicParsing
                Expand-Archive -Path $kongctlZip -DestinationPath $kongctlDir -Force
                Remove-Item $kongctlZip
                # Verify binary landed at expected path. Some releases nest inside a subdirectory.
                if (-not (Test-Path $kongctlPath)) {
                    $found = Get-ChildItem -Path $kongctlDir -Recurse -Filter 'kongctl.exe' | Select-Object -First 1
                    if ($found) {
                        Move-Item $found.FullName $kongctlPath
                        Write-Pass "kongctl downloaded and extracted to tools\konnect-cli\kongctl.exe"
                    } else {
                        Write-Warn "kongctl extracted but kongctl.exe not found in tools\konnect-cli\. Check the zip contents manually."
                    }
                } else {
                    Write-Pass "kongctl downloaded to tools\konnect-cli\"
                }
            } else {
                Write-Warn "Could not find kongctl Windows release asset. Download manually from https://github.com/Kong/kongctl/releases"
            }
        } catch {
            Write-Warn "kongctl download failed: $_. Download manually from https://github.com/Kong/kongctl/releases"
        }
    } else {
        Write-Pass "kongctl already present — skipping download"
    }
}

# ── Final summary ─────────────────────────────────────────────────────────────
Write-Host ""
Write-Host "── Summary " -ForegroundColor Cyan
Write-Host "   Pass: $passCount  Warn: $warnCount  Fail: $failCount"

if ($failCount -gt 0) {
    Write-Host ""
    Write-Host "   ❌ $failCount required tool(s) missing. Install them and re-run." -ForegroundColor Red
    Write-Host "      See docs/repo-setup.md for installation guidance." -ForegroundColor Yellow
    exit 1
}

if ($warnCount -gt 0) {
    Write-Host ""
    Write-Host "   ⚠️  Some credential files were created from templates." -ForegroundColor Yellow
    Write-Host "      Open each file and replace every <placeholder> value before use." -ForegroundColor Yellow
    Write-Host "      See docs/repo-setup.md for step-by-step instructions." -ForegroundColor Yellow
}

if ($failCount -eq 0 -and $warnCount -eq 0) {
    Write-Host ""
    Write-Host "   🎉 All checks passed. You're ready to go!" -ForegroundColor Green
}
